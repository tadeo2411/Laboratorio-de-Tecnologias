-- Taller 303 - Sistema de Control para Talleres Mecanicos
-- Esquema de la base de datos para PostgreSQL (16 o posterior)

CREATE DATABASE "taller-303";
\c "taller-303"
BEGIN;

CREATE TYPE "tipo_cliente" AS ENUM (
  'PERSONA',
  'EMPRESA'
);

CREATE TYPE "estado_turno" AS ENUM (
  'SOLICITADO',
  'CONFIRMADO',
  'CUMPLIDO',
  'AUSENTE',
  'CANCELADO'
);

CREATE TYPE "estado_orden" AS ENUM (
  'RECIBIDO',
  'DIAGNOSTICANDO',
  'ESPERANDO_APROBACION_PRESUPUESTO',
  'ESPERANDO_REPUESTO',
  'EN_REPARACION',
  'TERMINADO',
  'ENTREGADO',
  'CANCELADO'
);

CREATE TYPE "categoria_trabajo" AS ENUM (
  'MANTENIMIENTO',
  'REPARACION',
  'DIAGNOSTICO'
);

CREATE TYPE "estado_presupuesto" AS ENUM (
  'BORRADOR',
  'ENVIADO',
  'APROBADO',
  'CANCELADO'
);

CREATE TYPE "concepto_item" AS ENUM (
  'MANO_DE_OBRA',
  'REPUESTO'
);

CREATE TYPE "tipo_ficha" AS ENUM (
  'INGRESO',
  'EGRESO'
);

CREATE TYPE "conformidad_ficha" AS ENUM (
  'PENDIENTE',
  'APROBADA'
);

CREATE TYPE "tipo_valor_concepto" AS ENUM (
  'BOOLEANO',
  'NUMERO',
  'TEXTO'
);

CREATE TYPE "estado_aviso" AS ENUM (
  'PENDIENTE',
  'ENVIADO',
  'DESCARTADO'
);

CREATE TABLE "clientes" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "documento" varchar(11) NOT NULL UNIQUE,
  "tipo" tipo_cliente NOT NULL,
  "nombre" varchar(120) NOT NULL,
  "telefono" varchar(30) NOT NULL,
  "created_at" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "vehiculos" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "patente" varchar(7) UNIQUE NOT NULL,
  "marca" varchar(60) NOT NULL,
  "modelo" varchar(60) NOT NULL,
  "anio" integer NOT NULL,
  "descripcion" text,
  "kilometraje" integer NOT NULL,
  "created_at" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "duenos" (
  "id_cliente" integer,
  "id_vehiculo" integer,
  "ultima_visita" timestamp NOT NULL DEFAULT(now()),
  PRIMARY KEY ("id_cliente", "id_vehiculo")
);

CREATE TABLE "empleados" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre" varchar(120) NOT NULL,
  "usuario" varchar(50) UNIQUE NOT NULL,
  "password_hash" varchar(255) NOT NULL,
  "activo" boolean NOT NULL DEFAULT true
);

CREATE TABLE "roles" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre" varchar(60) UNIQUE NOT NULL
);

CREATE TABLE "permisos" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre" varchar(80) UNIQUE NOT NULL
);

CREATE TABLE "empleados_roles" (
  "empleado_id" integer NOT NULL,
  "rol_id" integer NOT NULL,
  PRIMARY KEY ("empleado_id", "rol_id")
);

CREATE TABLE "roles_permisos" (
  "rol_id" integer NOT NULL,
  "permiso_id" integer NOT NULL,
  PRIMARY KEY ("rol_id", "permiso_id")
);

CREATE TABLE "turnos" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_cliente" integer,
  "id_vehiculo" integer,
  "fecha_hora" timestamp NOT NULL,
  "duracion_min" integer NOT NULL DEFAULT 60,
  "motivo" text NOT NULL,
  "estado" estado_turno NOT NULL DEFAULT 'SOLICITADO',
  "created_at" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "ordenes_trabajo" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_cliente" integer,
  "id_vehiculo" integer,
  "turno_id" integer UNIQUE,
  "diagnostico" text,
  "estado" estado_orden NOT NULL DEFAULT 'RECIBIDO',
  "es_service" boolean NOT NULL DEFAULT false,
  "es_urgencia" boolean NOT NULL DEFAULT false,
  "garantia_dias" integer NOT NULL DEFAULT 15,
  "created_at" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "conceptos_ficha" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre" varchar(80) UNIQUE NOT NULL,
  "tipo_valor" tipo_valor_concepto NOT NULL,
  "activo" boolean NOT NULL DEFAULT true
);

CREATE TABLE "fichas" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "orden_id" integer NOT NULL,
  "tipo" tipo_ficha NOT NULL,
  "fecha" timestamp NOT NULL,
  "kilometraje" integer,
  "conformidad" conformidad_ficha NOT NULL DEFAULT 'PENDIENTE',
  "created_at" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "items_ficha" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "ficha_id" integer NOT NULL,
  "concepto_id" integer,
  "concepto" varchar(80) NOT NULL,
  "valor" varchar(255)
);

CREATE TABLE "fotos" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "item_ficha_id" integer NOT NULL,
  "ruta_archivo" varchar(255) NOT NULL,
  "created_at" timestamp NOT NULL DEFAULT (now())
);

CREATE TABLE "tipos_trabajo" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre" varchar(120) UNIQUE NOT NULL,
  "categoria" categoria_trabajo NOT NULL,
  "precio_estandar" decimal(12,2) NOT NULL,
  "activo" boolean NOT NULL DEFAULT true
);

CREATE TABLE "repuestos" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre" varchar(120) UNIQUE NOT NULL,
  "precio_estandar" decimal(12,2) NOT NULL,
  "activo" boolean NOT NULL DEFAULT true
);

CREATE TABLE "trabajos" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "orden_id" integer NOT NULL,
  "tipo_trabajo_id" integer NOT NULL,
  "descripcion" text,
  "mano_de_obra" decimal(12,2) NOT NULL
);

CREATE TABLE "repuestos_usados" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "trabajo_id" integer NOT NULL,
  "repuesto_id" integer NOT NULL,
  "cantidad" decimal(10,2) NOT NULL,
  "precio_unitario" decimal(12,2) NOT NULL
);

CREATE TABLE "trabajos_empleados" (
  "trabajo_id" integer NOT NULL,
  "empleado_id" integer NOT NULL,
  PRIMARY KEY ("trabajo_id", "empleado_id")
);

CREATE TABLE "presupuestos" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "numero" integer UNIQUE NOT NULL,
  "orden_id" integer NOT NULL,
  "fecha_emision" date NOT NULL,
  "vigencia_dias" integer NOT NULL,
  "estado" estado_presupuesto NOT NULL DEFAULT 'BORRADOR',
  "fecha_respuesta" date
);

CREATE TABLE "presupuesto_items" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "presupuesto_id" integer NOT NULL,
  "concepto" concepto_item NOT NULL,
  "descripcion" varchar(200) NOT NULL,
  "cantidad" decimal(10,2) NOT NULL,
  "precio_unitario" decimal(12,2) NOT NULL
);

CREATE TABLE "avisos_service" (
  "id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "id_vehiculo" integer,
  "fecha_prevista" date NOT NULL,
  "estado" estado_aviso NOT NULL DEFAULT 'PENDIENTE',
  "empleado_id" integer,
  "fecha_gestion" timestamp,
  "created_at" timestamp NOT NULL DEFAULT (now())
);

CREATE UNIQUE INDEX ON "fichas" ("orden_id", "tipo");

COMMENT ON COLUMN "clientes"."documento" IS 'DNI o CUIT, solo dígitos';

COMMENT ON COLUMN "clientes"."nombre" IS 'Nombre y apellido, o razón social';

COMMENT ON COLUMN "vehiculos"."patente" IS 'Mayúsculas, sin espacios: ABC123 o AB123CD';

COMMENT ON COLUMN "vehiculos"."descripcion" IS 'Detalles específicos que anota el taller';

COMMENT ON TABLE "duenos" IS 'Un vehículo puede figurar a nombre de más de un cliente (N:M)';

COMMENT ON COLUMN "empleados"."activo" IS 'Baja lógica: no se borra para no perder el historial';

COMMENT ON COLUMN "turnos"."id_cliente" IS 'Cliente que pide el turno';

COMMENT ON TABLE "ordenes_trabajo" IS 'Ingreso y egreso salen de las fichas. Garantía hasta = fecha de la ficha de egreso + garantia_dias';

COMMENT ON COLUMN "ordenes_trabajo"."id_cliente" IS 'Cliente que trae el vehículo: a quien se le envía el presupuesto';

COMMENT ON COLUMN "ordenes_trabajo"."turno_id" IS 'Vacío si el vehículo llegó sin turno';

COMMENT ON COLUMN "ordenes_trabajo"."diagnostico" IS 'Se va corrigiendo mientras se trabaja';

COMMENT ON COLUMN "ordenes_trabajo"."garantia_dias" IS 'Plazo congelado al abrir la orden (por defecto 15 días)';

COMMENT ON TABLE "conceptos_ficha" IS 'Lista configurable de lo que el taller revisa (RNF-07)';

COMMENT ON COLUMN "conceptos_ficha"."nombre" IS 'Ej.: Rayones, Nivel de combustible, Ruidos';

COMMENT ON COLUMN "fichas"."fecha" IS 'Fecha del hecho; puede cargarse después (RNF-03)';

COMMENT ON COLUMN "items_ficha"."concepto" IS 'Nombre congelado del concepto';

COMMENT ON TABLE "repuestos" IS 'No es un stock: se compran para cada trabajo';

COMMENT ON COLUMN "trabajos"."mano_de_obra" IS 'Precio congelado al cargar el trabajo';

COMMENT ON COLUMN "repuestos_usados"."cantidad" IS 'Decimal: ej. 4.5 litros de aceite';

COMMENT ON COLUMN "repuestos_usados"."precio_unitario" IS 'Precio congelado, no el del catálogo';

COMMENT ON TABLE "presupuestos" IS 'Vencido = fecha_emision + vigencia_dias. Total = suma de renglones';

COMMENT ON COLUMN "presupuestos"."vigencia_dias" IS 'Plazo congelado: se copia de configuracion al emitir';

COMMENT ON COLUMN "presupuestos"."fecha_respuesta" IS 'Cuando el cliente aprueba o rechaza';

COMMENT ON TABLE "presupuesto_items" IS 'Copia de los trabajos y repuestos de la orden al emitir';

COMMENT ON COLUMN "avisos_service"."empleado_id" IS 'Quién lo envió o descartó';

ALTER TABLE "empleados_roles" ADD FOREIGN KEY ("empleado_id") REFERENCES "empleados" ("id");

ALTER TABLE "empleados_roles" ADD FOREIGN KEY ("rol_id") REFERENCES "roles" ("id");

ALTER TABLE "roles_permisos" ADD FOREIGN KEY ("rol_id") REFERENCES "roles" ("id");

ALTER TABLE "roles_permisos" ADD FOREIGN KEY ("permiso_id") REFERENCES "permisos" ("id");

ALTER TABLE "items_ficha" ADD FOREIGN KEY ("concepto_id") REFERENCES "conceptos_ficha" ("id");

ALTER TABLE "trabajos" ADD FOREIGN KEY ("tipo_trabajo_id") REFERENCES "tipos_trabajo" ("id");

ALTER TABLE "repuestos_usados" ADD FOREIGN KEY ("repuesto_id") REFERENCES "repuestos" ("id");

ALTER TABLE "trabajos_empleados" ADD FOREIGN KEY ("empleado_id") REFERENCES "empleados" ("id");

ALTER TABLE "presupuestos" ADD FOREIGN KEY ("orden_id") REFERENCES "ordenes_trabajo" ("id");

ALTER TABLE "avisos_service" ADD FOREIGN KEY ("empleado_id") REFERENCES "empleados" ("id");

ALTER TABLE "duenos" ADD FOREIGN KEY ("id_cliente") REFERENCES "clientes" ("id") ON DELETE RESTRICT ON UPDATE CASCADE;

ALTER TABLE "duenos" ADD FOREIGN KEY ("id_vehiculo") REFERENCES "vehiculos" ("id") ON DELETE RESTRICT ON UPDATE CASCADE;

ALTER TABLE "turnos" ADD FOREIGN KEY ("id_cliente") REFERENCES "clientes" ("id") ON DELETE RESTRICT ON UPDATE CASCADE;

ALTER TABLE "turnos" ADD FOREIGN KEY ("id_vehiculo") REFERENCES "vehiculos" ("id") ON DELETE RESTRICT ON UPDATE CASCADE;

ALTER TABLE "ordenes_trabajo" ADD FOREIGN KEY ("id_cliente") REFERENCES "clientes" ("id") ON DELETE RESTRICT ON UPDATE CASCADE;

ALTER TABLE "ordenes_trabajo" ADD FOREIGN KEY ("id_vehiculo") REFERENCES "vehiculos" ("id") ON DELETE RESTRICT ON UPDATE CASCADE;

ALTER TABLE "avisos_service" ADD FOREIGN KEY ("id_vehiculo") REFERENCES "vehiculos" ("id") ON DELETE RESTRICT ON UPDATE CASCADE;

ALTER TABLE "ordenes_trabajo" ADD FOREIGN KEY ("turno_id") REFERENCES "turnos" ("id") ON DELETE RESTRICT;

ALTER TABLE "fichas" ADD FOREIGN KEY ("orden_id") REFERENCES "ordenes_trabajo" ("id") ON DELETE RESTRICT;

ALTER TABLE "items_ficha" ADD FOREIGN KEY ("ficha_id") REFERENCES "fichas" ("id") ON DELETE CASCADE;

ALTER TABLE "fotos" ADD FOREIGN KEY ("item_ficha_id") REFERENCES "items_ficha" ("id") ON DELETE CASCADE;

ALTER TABLE "trabajos" ADD FOREIGN KEY ("orden_id") REFERENCES "ordenes_trabajo" ("id") ON DELETE RESTRICT;

ALTER TABLE "repuestos_usados" ADD FOREIGN KEY ("trabajo_id") REFERENCES "trabajos" ("id") ON DELETE CASCADE;

ALTER TABLE "trabajos_empleados" ADD FOREIGN KEY ("trabajo_id") REFERENCES "trabajos" ("id") ON DELETE CASCADE;

ALTER TABLE "presupuesto_items" ADD FOREIGN KEY ("presupuesto_id") REFERENCES "presupuestos" ("id") ON DELETE CASCADE;

COMMIT;